"""Render a source page's JSON-owned character layout without scan access.

Output paths are drafts; publication/checkpoint updates remain a separate step.
Use --compare to check the exact bytes of an existing UTF-8 page.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / 'normalization'))
import read_page
from pages import renormalize_page
if __package__:
    from . import layout
else:
    import layout


def load_document(path):
    return json.loads(Path(path).read_bytes().decode('utf-8-sig'),
                      object_pairs_hook=read_page._pairs,
                      parse_constant=read_page._constant)


def generate(document, edits=None):
    """Return a detached JSON document and its generated text bytes."""
    raw = read_page.source_view(document)
    if edits is None:
        return document, layout.render(raw)
    changed, text = layout.patch_and_render(raw, edits)
    return (renormalize_page(changed, document) if read_page.is_uniform(document)
            else changed), text


def write_draft(path, data):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('xb') as stream:
        stream.write(data)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('model', type=Path)
    parser.add_argument('--compare', type=Path)
    parser.add_argument('--patches', type=Path,
                        help='Raw-view JSON-pointer edits with before/after values')
    parser.add_argument('--model-output', type=Path)
    parser.add_argument('--text-output', type=Path)
    args = parser.parse_args()
    if args.patches and not (args.model_output and args.text_output):
        parser.error('--patches requires both draft output paths')
    outputs = [p.resolve() for p in (args.model_output, args.text_output) if p]
    if len(set(outputs)) != len(outputs) or any(p.exists() for p in outputs):
        parser.error('Draft outputs must be distinct, new files')
    document, text = generate(load_document(args.model),
                              load_document(args.patches) if args.patches else None)
    if args.compare and args.compare.read_bytes() != text:
        raise ValueError('Generated bytes differ from ' + str(args.compare))
    if args.model_output:
        data = (json.dumps(document, ensure_ascii=False, sort_keys=True,
                           separators=(',', ':'), allow_nan=False) + '\n').encode('utf-8')
        write_draft(args.model_output, data)
    if args.text_output:
        write_draft(args.text_output, text)
    print(json.dumps({'passed': True, 'bytes': len(text),
                      'sha256': hashlib.sha256(text).hexdigest(),
                      'exact_comparison': bool(args.compare),
                      'canonical_publication': False}))


if __name__ == '__main__':
    main()
